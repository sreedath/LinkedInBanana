"""Style guidelines for LinkedIn playlist summary images."""

from __future__ import annotations

DEFAULT_LINKEDIN_GUIDELINES = """\
# LinkedIn Playlist Summary Image — Aesthetic Guidelines

## 1. The "LinkedIn Look"

LinkedIn images must be professional, bold, and immediately readable in a fast-scrolling
mobile feed. The design should communicate value at a glance — think "conference slide"
meets "premium infographic." High contrast, clean typography, and strategic use of color
are essential.

## 2. Color Philosophy

### Professional Palettes
- **Primary**: Deep navy, charcoal, or dark teal as a dominant anchor color
- **Accent**: One vibrant accent color — coral, electric blue, golden amber, or emerald
- **Background**: Clean white, very light grey, or deep dark for contrast
- **Text on dark**: White or very light text on dark backgrounds
- **Text on light**: Dark charcoal or navy text on light backgrounds

### Color Rules
- Maximum 3-4 colors per image (1 dominant, 1 accent, 1-2 supporting)
- Use accent color for key numbers, highlights, and CTAs
- Describe colors in natural language (NEVER hex codes or CSS values)
- Ensure WCAG AA contrast ratio between text and backgrounds

## 3. Typography

### Hierarchy
- **Title**: Large, bold sans-serif. Must be readable at 400px width (mobile feed)
- **Subtitles**: Medium weight, slightly smaller
- **Body/Stats**: Clean, readable. Numbers should be bold and prominent
- **Annotations**: Small but still legible at feed size

### Rules
- Sans-serif fonts only (modern, professional feel)
- Maximum 2 font weights per image (bold + regular)
- Minimum visual text size equivalent to 16pt at final display size
- Title should occupy 15-20% of image height

## 4. Layout Principles

### Composition
- Clear visual hierarchy: eye should flow from title → key stat → details
- Generous whitespace — at least 10% margins on all sides
- Align elements to an invisible grid for clean edges
- Group related items visually with proximity and background fills

### Content Density
- Maximum 6-8 distinct text elements per image
- One clear focal point (the main message or number)
- Supporting details should complement, not compete with, the focal point

## 5. Visual Elements

### Do Use
- Rounded rectangles with subtle shadows for card-like sections
- Simple, geometric icons for topics/categories
- Subtle separating lines (thin, light grey)
- Numbered lists or step indicators for sequential content
- Bold stat callouts with large numbers and small labels

### Do NOT Use
- Stock photo backgrounds
- Gradients that reduce text readability
- 3D effects, drop shadows on text, or decorative borders
- Clip art or cartoon illustrations
- More than one decorative element type

## 6. LinkedIn-Specific Optimization

- Image should convey its message even without the caption
- Key information in the center 80% (edges may be cropped on some devices)
- Include the playlist title prominently — it's the hook
- Video count and total duration as visual badges/callouts
- Channel name as a subtle attribution, not the focus
"""
